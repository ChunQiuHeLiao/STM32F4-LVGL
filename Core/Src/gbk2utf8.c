#define TABLE_SIZE (sizeof(gbk_unicode_table) / sizeof(gbk_unicode_map_t))



/* ----------------------------- 二分查找 ----------------------------- */
/**
 * @brief 根据 GBK 编码查找对应的 Unicode 码点
 * @param gbk 待查找的 GBK 编码（高字节在前）
 * @return 对应的 Unicode 码点，若未找到则返回 0xFFFD（'�'）
 */
static uint16_t gbk_to_unicode(uint16_t gbk) {
    int left = 0, right = TABLE_SIZE - 1;
    while (left <= right) {
        int mid = (left + right) >> 1;
        if (gbk_unicode_table[mid].gbk == gbk) {
            return gbk_unicode_table[mid].unicode;
        } else if (gbk_unicode_table[mid].gbk < gbk) {
            left = mid + 1;
        } else {
            right = mid - 1;
        }
    }
    return 0xFFFD;  // 未找到返回替换字符 '�'
}

/* ----------------------------- UTF-8 编码转换 ----------------------------- */
/**
 * @brief 将单个 Unicode 码点编码为 UTF-8 字节序列
 * @param unicode Unicode 码点
 * @param out     输出缓冲区（至少 4 字节）
 * @return 编码后的 UTF-8 字节数（1~3）
 */
static int unicode_to_utf8(uint16_t unicode, uint8_t *out) {
    if (unicode <= 0x7F) {
        out[0] = (uint8_t)unicode;
        return 1;
    } else if (unicode <= 0x7FF) {
        out[0] = (uint8_t)(0xC0 | ((unicode >> 6) & 0x1F));
        out[1] = (uint8_t)(0x80 | (unicode & 0x3F));
        return 2;
    } else {  // unicode <= 0xFFFF
        out[0] = (uint8_t)(0xE0 | ((unicode >> 12) & 0x0F));
        out[1] = (uint8_t)(0x80 | ((unicode >> 6) & 0x3F));
        out[2] = (uint8_t)(0x80 | (unicode & 0x3F));
        return 3;
    }
}

/* ----------------------------- 主转换函数 ----------------------------- */
/**
 * @brief GBK 字符串转 UTF-8 字符串
 * @param gbk_str   输入 GBK 字符串（以 '\0' 结尾）
 * @param utf8_str  输出 UTF-8 字符串缓冲区
 * @param max_len   输出缓冲区的最大字节数（建议至少为输入长度的 2 倍）
 * @return 转换后的 UTF-8 字符串实际字节数（不含结尾 '\0'），若出错返回 -1
 * @note  未映射的 GBK 字符将被替换为 '?'（ASCII 0x3F）
 * @note  支持 ASCII 字符（0x00~0x7F）原样拷贝
 */
uint16_t gbk_to_utf8(const uint8_t *gbk_str, uint8_t *utf8_str, uint16_t max_len) 
{
    if (!gbk_str || !utf8_str || max_len <= 0) return -1;

    int out_len = 0;
    while (*gbk_str) {
        uint8_t c = *gbk_str;
        if (c < 0x80) {
            /* ASCII 字符直接复制 */
            if (out_len + 1 >= max_len) break;
            utf8_str[out_len++] = c;
            gbk_str++;
        } else {
            /* GBK 双字节字符 */
            uint8_t high = c;
            uint8_t low = *(gbk_str + 1);
            if (low == 0) break;   // 字符串意外结束
            uint16_t gbk_code = ((uint16_t)high << 8) | low;
            uint16_t unicode = gbk_to_unicode(gbk_code);
            uint8_t utf8_buf[4];
            int utf8_len;
            if (unicode == 0xFFFD) {
                /* 未映射的字符替换为 '?' */
                utf8_buf[0] = '?';
                utf8_len = 1;
            } else {
                utf8_len = unicode_to_utf8(unicode, utf8_buf);
            }
            if (out_len + utf8_len >= max_len) break;
            for (int i = 0; i < utf8_len; i++) {
                utf8_str[out_len++] = utf8_buf[i];
            }
            gbk_str += 2;
        }
    }
    utf8_str[out_len] = '\0';
    return out_len;
}

