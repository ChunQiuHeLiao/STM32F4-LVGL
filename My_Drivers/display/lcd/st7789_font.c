/// @brief 获取单个汉字的编号
/// @param str 单个汉字
/// @return 返回序号
uint8_t Font_GetFontId(uint8_t* str)
{
    for(uint8_t i=0;i<44;i++)
    {
        if(str[0]==Chinese40X56[i][FONT_DATA_SIZE+0]&&str[1]==Chinese40X56[i][FONT_DATA_SIZE+1]&&str[2]==Chinese40X56[i][FONT_DATA_SIZE+2])
        return i;
    }
}



